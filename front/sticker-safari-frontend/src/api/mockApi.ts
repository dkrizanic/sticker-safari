const generateAlbum = (id: number, name: string, dataSource: Sticker[]): Album => {
    const stickers = dataSource.map((sticker) => sticker);

    return {
        id,
        name,
        stickers,
    };
};

const generateMockAlbums = (): Album[] => {
    const album1 = generateAlbum(1, "Zivotinjsko carstvo", ZCData);
    const album2 = generateAlbum(2, "Zvjerici", ZvjericiData);

    return [album1, album2];
};

const mockOpenPack = (albumId: string, stickerNumber: number): Sticker[] => {
    const openedStickers: Sticker[] = []

    for (let i = 0; i < stickerNumber; i++) {
        switch(albumId){
            case "1":
                openedStickers.push(ZCData[Math.floor(Math.random() * ZCData.length)]);
                break;
            case "2":
                openedStickers.push(ZvjericiData[Math.floor(Math.random() * ZvjericiData.length)]);
                break;
        }
    }

    return openedStickers;
}

interface MockApi {
  getAlbums: () => Promise<Album[]>;
  openPack: (albumId: string, stickerNumber: number) => Promise<Sticker[]>;
}

